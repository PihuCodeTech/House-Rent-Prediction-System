"""Build reports/deep_tuning_report.md from reports/deep_tuning/*.csv (written by scripts/deep_tune.py).
Reads result files only (pandas), so it runs anywhere the CSVs are."""
import json, pathlib
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / "reports" / "deep_tuning"
f0 = lambda x: f"{x:,.0f}"
pm = lambda m, s: f"{m:,.0f} ± {s:,.0f}"


def main():
    s = pd.read_csv(D / "deep_tuning_summary.csv")
    params = json.loads((D / "deep_tuned_params.json").read_text())
    L = ["# Deep Hyperparameter Tuning — XGBoost & Random Forest", "",
         "_Generated by `scripts/deep_tuning_report.py` from `reports/deep_tuning/`._", "",
         "**Method.** Optuna (TPE, seed 42) on the training split only; objective = repeated 5-fold CV RMSE "
         "(XGBoost 2x5, Random Forest 1x5). The top 5 trials, the library default and the earlier tuned config "
         "(`tuned_v1`) were then re-scored on the same fresh repeated 5x3 folds (seed 7) the search never saw; the "
         "deep config is the best of those. Validation and test were not used for any choice.", "",
         "± = bootstrap std over rows (train, test), fold std (5-fold CV, fresh-fold CV).", ""]
    for key, g in s.groupby("key", sort=False):
        L += [f"## {g['model'].iloc[0]}", "",
              "| Config | Train RMSE | 5-fold CV RMSE | Fresh-fold CV (5x3) | Val RMSE | Test RMSE | Test MAE | Test R² | CV − Train gap |",
              "|---|--:|--:|--:|--:|--:|--:|--:|--:|"]
        for _, r in g.iterrows():
            L.append(f"| {r.variant} | {pm(r.train_rmse, r.train_rmse_std)} | {pm(r.cv_rmse, r.cv_rmse_std)} | "
                     f"{pm(r.confirm_rep_cv_rmse, r.confirm_rep_cv_sd)} | {f0(r.val_rmse)} | {pm(r.test_rmse, r.test_rmse_std)} | "
                     f"{pm(r.test_mae, r.test_mae_std)} | {r.test_r2:.3f} ± {r.test_r2_std:.3f} | {f0(r.train_cv_gap)} |")
        L += ["", "Deep-tuned hyperparameters: `" + json.dumps({k: (round(v, 4) if isinstance(v, float) else v)
                                                              for k, v in params[key].items()}) + "`", ""]
    if (D / "same_folds_comparison.csv").exists():
        c = pd.read_csv(D / "same_folds_comparison.csv")
        L += ["## Where the leaders stand on identical fresh folds (repeated 5x3, seed 7)", "",
              "| Model | Config | Fresh-fold CV RMSE |", "|---|---|--:|"]
        L += [f"| {r.key} | {r.config} | {pm(r.confirm_rep_cv_rmse, r.confirm_rep_cv_sd)} |" for _, r in c.iterrows()]
        L += [""]
    if (D / "paired_bootstrap.csv").exists():
        b = pd.read_csv(D / "paired_bootstrap.csv")
        pcol = [c for c in b.columns if c.startswith("P(")][0]
        L += ["## Are the validation / test differences real? (paired bootstrap, 2,000 resamples)", "",
              "| Model | Split | Comparison | RMSE difference | 95% CI of difference | P(deep better) |", "|---|---|---|--:|--:|--:|"]
        L += [f"| {r.model} | {r.split} | {r.comparison} | {r.rmse_diff:+,.0f} | {r.diff_95ci_low:+,.0f} to {r.diff_95ci_high:+,.0f} | {r[pcol]:.2f} |"
              for _, r in b.iterrows()]
        L += ["", "A difference whose interval crosses zero is not statistically distinguishable from noise.", ""]
    L += ["Untuned fully grown trees (Random Forest default) differ slightly across CPU architectures; the tuned "
          "and deep-tuned configurations reproduce exactly. Reproduce: `python scripts/deep_tune.py` then "
          "`python scripts/deep_tuning_report.py`."]
    (ROOT / "reports" / "deep_tuning_report.md").write_text("\n".join(L))
    print("-> reports/deep_tuning_report.md")


if __name__ == "__main__":
    main()
